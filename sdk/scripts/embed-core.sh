#!/bin/sh
# Copies files from core into the Valdi modules as TypeScript string constants.
# (A Valdi module only accepts .ts/.tsx sources, so a .js or .json file is inlined as text.)
#   dist/prism-runtime.js  ->  modules/prism_core/src/PrismRuntimeSource.ts   (runtime + block specs)
#   tokens.json       ->  modules/prism_theme/src/TokensSource.ts   (as a TS object: it's plain data)
# Run after the runtime or the tokens change (npm run build in core first).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
CORE="$HERE/../../core"
MODS="$HERE/../modules"
(cd "$CORE" && npm run build > /dev/null)   # always fresh: the runtime carries the block specs
embed() { # embed <source file> <output .ts> <constant name>
  node -e '
    const fs = require("fs");
    const [src, out, name] = process.argv.slice(1);
    const text = fs.readFileSync(src, "utf8");
    fs.writeFileSync(out, "// GENERATED by sdk/scripts/embed-core.sh from core. Do not edit.\n" +
      "export const " + name + ": string = " + JSON.stringify(text) + ";\n");
    console.log("wrote " + out);
  ' "$1" "$2" "$3"
}
embed "$CORE/dist/prism-runtime.js" "$MODS/prism_core/src/PrismRuntimeSource.ts" PRISM_RUNTIME_JS

# Tokens are plain data, so they become a TypeScript object (no parsing on the phone, and typed).
node -e '
  const fs = require("fs");
  const [src, out] = process.argv.slice(1);
  const tokens = JSON.parse(fs.readFileSync(src, "utf8"));
  fs.writeFileSync(out, "// GENERATED by sdk/scripts/embed-core.sh from core/dist/tokens.json. Do not edit.\n" +
    "export const TOKENS = " + JSON.stringify(tokens, null, 2) + " as const;\n");
  console.log("wrote " + out);
' "$CORE/dist/tokens.json" "$MODS/prism_theme/src/TokensSource.ts"

# The three version numbers (core/dist/versions.json, VERSIONS.md) as constants in each wrapper,
# so an app can tell its server what it draws: { "blocks": 2, "library": "1.6.0" }.
node -e '
  const fs = require("fs");
  const [src, ios, android, flutter] = process.argv.slice(1);
  const v = JSON.parse(fs.readFileSync(src, "utf8"));
  const note = "GENERATED by sdk/scripts/embed-core.sh from core/dist/versions.json. Do not edit.";
  fs.writeFileSync(ios, `// ${note}

/// What this SDK draws (VERSIONS.md). Send \`PrismVersions.app\` to your server with each chat
/// request, so the AI only uses parts this app can draw.
public enum PrismVersions {
    /// The basic blocks this SDK\x27s drawer draws.
    public static let blocks = ${v.blocks}
    /// The part library built into this SDK (a newer one can come from the server).
    public static let library = "${v.library}"
    /// The message format this SDK reads.
    public static let format = ${v.format}
    /// For the request body: \`["blocks": ${v.blocks}, "library": "${v.library}"]\`.
    public static var app: [String: Any] { ["blocks": blocks, "library": library] }
}
`);
  fs.writeFileSync(android, `// ${note}
package dev.prism.android

/**
 * What this SDK draws (VERSIONS.md). Send [app] to your server with each chat request, so the AI
 * only uses parts this app can draw.
 */
object PrismVersions {
    /** The basic blocks this SDK\x27s drawer draws. */
    const val BLOCKS = ${v.blocks}
    /** The part library built into this SDK (a newer one can come from the server). */
    const val LIBRARY = "${v.library}"
    /** The message format this SDK reads. */
    const val FORMAT = ${v.format}
    /** For the request body: {"blocks": ${v.blocks}, "library": "${v.library}"}. */
    val app: Map<String, Any> get() = mapOf("blocks" to BLOCKS, "library" to LIBRARY)
}
`);
  fs.writeFileSync(flutter, `// ${note}

/// What this SDK draws (VERSIONS.md). Send [PrismVersions.app] to your server with each chat
/// request, so the AI only uses parts this app can draw.
abstract final class PrismVersions {
  /// The basic blocks this SDK\x27s drawer draws.
  static const blocks = ${v.blocks};

  /// The part library built into this SDK (a newer one can come from the server).
  static const library = \x27${v.library}\x27;

  /// The message format this SDK reads.
  static const format = ${v.format};

  /// For the request body: {"blocks": ${v.blocks}, "library": "${v.library}"}.
  static Map<String, Object> get app => {\x27blocks\x27: blocks, \x27library\x27: library};
}
`);
  console.log("wrote version constants");
' "$CORE/dist/versions.json" "$HERE/../ios/Sources/Prism/PrismVersions.swift" \
  "$HERE/../android/prism/src/main/java/dev/prism/android/PrismVersions.kt" "$HERE/../flutter/lib/src/prism_versions.dart"
